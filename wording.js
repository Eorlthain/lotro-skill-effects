function W(key, ) {
  var line = WORDING[key];
  var vals = Array.prototype.slice.call(arguments, 1);
  if (!line) return "";
  var parts = line.parts, bound = {}, out = [], keep = false, i;

  for (i = 0; i < parts.length; i++) if (parts[i].indexOf("{{keepspaces}}") >= 0) keep = true;

  for (i = 0; i < parts.length; i++) {
    var tagRe = /#(-?\d+):/g, tm;
    while ((tm = tagRe.exec(parts[i])) !== null) {
      var tn = parseInt(tm[1], 10), src = vals[i];
      if (tn === -1) {
        bound[-1] = (src && src.length !== undefined && typeof src !== "string") ? src.length : src;
      } else if (!(tn in bound)) {
        bound[tn] = src;
      }
    }
  }
  for (i = 0; i < vals.length; i++) {
    if (!((i + 1) in bound)) bound[i + 1] = vals[i];
  }

  function pick(options, count) {
    var opts = options.split("|"), dflt = null;
    var shown = (count === undefined || count === null) ? "" : String(count).trim();
    for (var j = 0; j < opts.length; j++) {
      var m = /^(.*?)\[([0-9.]+)\]$/.exec(opts[j]);
      if (m) { if (shown && shown === m[2]) return m[1]; }
      else dflt = opts[j];
    }
    return dflt === null ? opts[0] : dflt;
  }

  for (i = 0; i < parts.length; i++) {
    var text = parts[i].split("{{keepspaces}}").join("");
    text = text.replace(/\{([^{}]*\|[^{}]*)\}/g, function (whole, options, at) {
      var before = text.slice(0, at), tags = before.match(/#(-?\d+):/g), n;
      n = tags ? parseInt(tags[tags.length - 1].slice(1), 10) : (i || 1);
      return pick(options, bound[n]);
    });
    out.push(text.replace(/#(-?\d+):/g, ""));
    if (i < parts.length - 1) {
      var val = vals[i];
      if (val && val.length !== undefined && typeof val !== "string") val = Array.prototype.join.call(val, ", ");
      out.push(val === undefined || val === null ? "" : String(val));
    }
  }
  var s = out.join("");
  s = keep ? s : s.replace(/\s+/g, " ").replace(/\s+([.,;:!?])/g, "$1").trim();

  return s.replace(/<\/?rgb[^>]*>/g, "");
}

function wLead(key) {
  var line = WORDING[key];
  if (!line || line.parts.length < 2) return null;
  var lead = line.parts[0].replace(/<\/?rgb[^>]*>/g, "").trim();
  return lead || null;
}

function tipW(host, key, cls ) {
  var vals = Array.prototype.slice.call(arguments, 3);
  var whole = W.apply(null, [key].concat(vals));
  if (!whole) return;
  var lead = wLead(key);
  if (lead && whole.indexOf(lead) === 0) {
    tipLine(host, lead, whole.slice(lead.length).trim(), cls);
  } else {
    tipLine(host, null, whole, cls);
  }
}
